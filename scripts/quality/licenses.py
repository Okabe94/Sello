"""The release build's runtime libraries and their licences, from the locked dependencies.

Every `releaseRuntimeClasspath` entry in app/gradle.lockfile is matched against the
reviewed table in release-licenses.json. `check` (G3) fails when a library has no
reviewed licence or docs/release/dependencies.md no longer lists exactly these
libraries; `write` regenerates the list after a review. Offline: nothing is fetched.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCKFILE = Path("app/gradle.lockfile")
TABLE = Path(__file__).with_name("release-licenses.json")
LISTING = Path("docs/release/dependencies.md")
CONFIGURATION = "releaseRuntimeClasspath"


class LicenceError(Exception):
    pass


def release_modules(lockfile_text):
    """(group, name, version) for every locked module of the release runtime."""
    modules = []
    for line in lockfile_text.splitlines():
        if line.startswith("#") or "=" not in line:
            continue
        coordinates, configurations = line.split("=", 1)
        if CONFIGURATION in configurations.split(","):
            group, name, version = coordinates.split(":")
            modules.append((group, name, version))
    return sorted(modules)


def licence(table, group, name):
    module = table.get("modules", {}).get(f"{group}:{name}")
    if module:
        return module
    matches = [prefix for prefix in table.get("groups", {})
               if group == prefix or group.startswith(prefix + ".")]
    if not matches:
        return None
    return table["groups"][max(matches, key=len)]


def listing(modules, table):
    unknown = [f"{g}:{n}" for g, n, _ in modules if licence(table, g, n) is None]
    if unknown:
        raise LicenceError("no reviewed licence for " + ", ".join(unknown) + f"; review and add it to {TABLE.name}")
    counts = {}
    for group, name, _ in modules:
        counts[licence(table, group, name)] = counts.get(licence(table, group, name), 0) + 1
    lines = [
        "# Release dependencies",
        "",
        "Generated by `python3 scripts/quality/licenses.py write` from `app/gradle.lockfile`",
        f"(`{CONFIGURATION}`) and the reviewed table `scripts/quality/release-licenses.json`.",
        "G3 fails when this list no longer matches the locked libraries. Do not edit by hand.",
        "",
        "| Licence | Libraries |",
        "| --- | --- |",
        *(f"| {name} | {count} |" for name, count in sorted(counts.items())),
        "",
        "| Library | Version | Licence |",
        "| --- | --- | --- |",
        *(f"| `{g}:{n}` | {v} | {licence(table, g, n)} |" for g, n, v in modules),
        "",
    ]
    return "\n".join(lines)


def render(root):
    modules = release_modules((Path(root) / LOCKFILE).read_text(encoding="utf-8"))
    if not modules:
        raise LicenceError(f"no {CONFIGURATION} entries in {LOCKFILE}")
    return listing(modules, json.loads(TABLE.read_text(encoding="utf-8")))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=("check", "write"))
    args = parser.parse_args(argv)
    try:
        text = render(ROOT)
    except (LicenceError, OSError, ValueError) as error:
        print(f"FAILED: {error}", file=sys.stderr)
        return 1
    target = ROOT / LISTING
    if args.action == "write":
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        print(f"Wrote {LISTING}")
        return 0
    if not target.is_file() or target.read_text(encoding="utf-8") != text:
        print(f"FAILED: {LISTING} does not match the locked release libraries; review, then run `licenses.py write`",
              file=sys.stderr)
        return 1
    print(f"{LISTING}: {text.count('| `')} libraries, each with a reviewed licence")
    return 0


if __name__ == "__main__":
    sys.exit(main())
